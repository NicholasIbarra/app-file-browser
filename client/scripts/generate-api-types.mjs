import { mkdir, writeFile } from 'node:fs/promises'
import { request } from 'node:https'
import { dirname, resolve } from 'node:path'
import process from 'node:process'
import openapiTS, { astToString } from 'openapi-typescript'

const schemaUrl = new URL(
  process.env.OPENAPI_SCHEMA_URL ??
    'https://localhost:7246/swagger/v1/swagger.json',
)
const outputPath = resolve('src/api/generated/schema.ts')

if (!['localhost', '127.0.0.1', '::1'].includes(schemaUrl.hostname)) {
  throw new Error(
    'OPENAPI_SCHEMA_URL must point to localhost because development TLS validation is disabled for this request.',
  )
}

function fetchLocalSchema(url) {
  return new Promise((resolveSchema, rejectSchema) => {
    const schemaRequest = request(
      url,
      { rejectUnauthorized: false },
      (response) => {
        if (response.statusCode !== 200) {
          response.resume()
          rejectSchema(
            new Error(`Failed to fetch OpenAPI schema: HTTP ${response.statusCode}`),
          )
          return
        }

        response.setEncoding('utf8')
        let body = ''
        response.on('data', (chunk) => {
          body += chunk
        })
        response.on('end', () => {
          try {
            resolveSchema(JSON.parse(body))
          } catch (error) {
            rejectSchema(error)
          }
        })
      },
    )

    schemaRequest.on('error', rejectSchema)
    schemaRequest.end()
  })
}

const schema = await fetchLocalSchema(schemaUrl)
const generatedTypes = astToString(await openapiTS(schema))

await mkdir(dirname(outputPath), { recursive: true })
await writeFile(
  outputPath,
  `/**\n * This file was auto-generated by openapi-typescript.\n * Do not make direct changes to the file.\n */\n\n${generatedTypes}`,
)

console.log(`Generated ${outputPath} from ${schemaUrl}`)
